/**
 * The built-in code tables of StuffIt method 13.
 *
 * A stream may carry its own Huffman code lengths, but most do not: five sets
 * of lengths are baked into the format, tuned by Aladdin on five kinds of data,
 * and a stream picks one by number. They are unreadable as data and there is
 * nothing to derive them from — they are simply what the encoder used, and a
 * decoder that does not have them cannot read those streams at all.
 *
 * `first` is the code used after a literal, `second` the one used after a
 * match, and `offset` codes the bit-width of the match distance. Transcribed
 * from XADMaster's `XADStuffIt13Handle.m` — see THIRD_PARTY_NOTICES.
 */

export type CodeTables = {
  readonly first: readonly number[];
  readonly second: readonly number[];
  readonly offset: readonly number[];
};

